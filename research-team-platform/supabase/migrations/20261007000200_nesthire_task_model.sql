create or replace function private.valid_links(p_links text[])
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(cardinality(p_links), 0) <= 10
     and not exists (
       select 1 from unnest(coalesce(p_links, '{}'::text[])) as l
       where l !~ '^https?://[^\s]+$' or char_length(l) > 2048
     );
$$;

