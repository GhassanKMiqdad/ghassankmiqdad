-- =============================================================================
-- NestHire upgrade 2/5 — task scheduling and execution model
--
--   * Lifecycle: NOT_STARTED → SCHEDULED → IN_PROGRESS → SUBMITTED →
--     UNDER_REVIEW → (REVISION_REQUIRED → IN_PROGRESS/SUBMITTED …) →
--     APPROVED → COMPLETED, plus BLOCKED and CANCELLED.
--     Existing rows are migrated: todo → not_started, review → submitted,
--     rejected → cancelled.
--   * Priorities P0 (critical) … P3 (low). Existing rows: critical → p0,
--     high → p1, medium → p2, low → p3.
--   * Scheduling: planned start, duration (+ unit, normalized to minutes),
--     due date/time (start + duration, calculated by the server unless a
--     supervisor overrides it), planning month/week (the plan, distinct from
--     actual dates) and the actual execution timestamps.
--   * Task ID (task_code), e.g. M01-GH-01-01: unique, immutable, generated by
--     the server unless a supervisor enters an existing ID.
--   * Visibility: PRIVATE until a reviewer marks the approved task as
--     completed; then a sanitized publication is created for the team.
--   * Versioned submissions, review records, dependencies, notifications.
--
-- The enum types are replaced (not extended with ADD VALUE) so the whole
-- upgrade can run inside one transaction (SQL Editor bundle).
-- =============================================================================

